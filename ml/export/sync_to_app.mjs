#!/usr/bin/env node
// Converts ml/export/artifacts/model_weights.json into a plain TS module so it
// bundles into the app the same way as any other source file — no runtime
// JSON-import machinery to get right across tsc/Node-ESM/Metro.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WEIGHTS_SRC = path.join(__dirname, "artifacts", "model_weights.json");
const WEIGHTS_DEST = path.resolve(__dirname, "../../packages/detector/src/model.weights.ts");
const METRICS_SRC = path.resolve(__dirname, "../training/artifacts/metrics.json");
const METRICS_DEST = path.resolve(__dirname, "../../packages/detector/src/model.metrics.ts");

const weights = JSON.parse(readFileSync(WEIGHTS_SRC, "utf-8"));

const weightsContents = `// GENERATED by ml/export/sync_to_app.mjs from ml/export/artifacts/model_weights.json — do not hand-edit.
// Regenerate: python ml/training/train.py && python ml/export/export_model.py && node ml/export/sync_to_app.mjs

export interface ModelDenseLayer {
  weights: number[][];
  bias: number[];
  activation: "relu" | "softmax";
}

export interface ModelWeights {
  modelVersion: string;
  featureOrder: string[];
  labels: string[];
  normalization: { mean: number[]; variance: number[]; epsilon: number };
  layers: ModelDenseLayer[];
}

export const MODEL_WEIGHTS: ModelWeights = ${JSON.stringify(weights)};
`;

writeFileSync(WEIGHTS_DEST, weightsContents);
console.log(`Wrote ${WEIGHTS_DEST} (${weightsContents.length} bytes)`);

const metrics = JSON.parse(readFileSync(METRICS_SRC, "utf-8"));

const metricsContents = `// GENERATED by ml/export/sync_to_app.mjs from ml/training/artifacts/metrics.json — do not hand-edit.
// Regenerate: python ml/training/train.py && node ml/export/sync_to_app.mjs
// Real numbers from the actual training run — see ml/training/train.py for the eval code.

export interface ClassMetric {
  precision: number;
  recall: number;
  f1Score: number;
  support: number;
}

export interface ModelMetrics {
  featureOrder: string[];
  labels: string[];
  testAccuracy: number;
  testLoss: number;
  potholeFalsePositiveRate: number;
  perClass: Record<string, ClassMetric>;
  /** rows = true label, columns = predicted label, same order as \`labels\`. */
  confusionMatrix: number[][];
  datasetSize: number;
  trainSize: number;
  valSize: number;
  testSize: number;
  note: string;
}

export const MODEL_METRICS: ModelMetrics = {
  featureOrder: ${JSON.stringify(metrics.feature_order)},
  labels: ${JSON.stringify(metrics.labels)},
  testAccuracy: ${metrics.test_accuracy},
  testLoss: ${metrics.test_loss},
  potholeFalsePositiveRate: ${metrics.pothole_false_positive_rate},
  perClass: ${JSON.stringify(
    Object.fromEntries(
      metrics.labels.map((label) => [
        label,
        {
          precision: metrics.classification_report[label].precision,
          recall: metrics.classification_report[label].recall,
          f1Score: metrics.classification_report[label]["f1-score"],
          support: metrics.classification_report[label].support,
        },
      ])
    )
  )},
  confusionMatrix: ${JSON.stringify(metrics.confusion_matrix)},
  datasetSize: ${metrics.dataset_size},
  trainSize: ${metrics.train_size},
  valSize: ${metrics.val_size},
  testSize: ${metrics.test_size},
  note: ${JSON.stringify(metrics.note)},
};
`;

writeFileSync(METRICS_DEST, metricsContents);
console.log(`Wrote ${METRICS_DEST} (${metricsContents.length} bytes)`);
