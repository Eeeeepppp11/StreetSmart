#!/usr/bin/env node
// Converts ml/export/artifacts/model_weights.json into a plain TS module so it
// bundles into the app the same way as any other source file — no runtime
// JSON-import machinery to get right across tsc/Node-ESM/Metro.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(__dirname, "artifacts", "model_weights.json");
const DEST = path.resolve(__dirname, "../../packages/detector/src/model.weights.ts");

const weights = JSON.parse(readFileSync(SRC, "utf-8"));

const contents = `// GENERATED by ml/export/sync_to_app.mjs from ml/export/artifacts/model_weights.json — do not hand-edit.
// Regenerate: python ml/training/train.py && python ml/export/export_model.py && node ml/export/sync_to_app.mjs

export interface ModelDenseLayer {
  weights: number[][];
  bias: number[];
  activation: "relu" | "softmax";
}

export interface ModelWeights {
  modelVersion: string;
  featureOrder: string[];
  labels: string[];
  normalization: { mean: number[]; variance: number[]; epsilon: number };
  layers: ModelDenseLayer[];
}

export const MODEL_WEIGHTS: ModelWeights = ${JSON.stringify(weights)};
`;

writeFileSync(DEST, contents);
console.log(`Wrote ${DEST} (${contents.length} bytes)`);
